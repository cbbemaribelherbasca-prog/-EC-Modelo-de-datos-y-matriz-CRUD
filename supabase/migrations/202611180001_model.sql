-- Modelo del PDF. No modifica tablas preexistentes ni elimina datos.
create table public.products (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  audience text not null check (audience in ('Hombre','Mujer','Niños')),
  style text not null check (style in ('Running','Urbano','Casual')),
  color text not null check (length(btrim(color)) between 1 and 120),
  price numeric(10,2) not null check (price > 0),
  old_price numeric(10,2) check (old_price > price),
  image_path text not null check (length(image_path) between 1 and 500 and image_path !~* '^(javascript|data):'),
  badge text not null default '' check (length(badge) <= 40),
  description text not null check (length(btrim(description)) between 1 and 1500),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table public.favorites (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);
create table public.cart_items (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  size smallint not null check (size between 35 and 42),
  qty smallint not null default 1 check (qty between 1 and 10),
  updated_at timestamptz not null default now(),
  primary key (user_id, product_id, size)
);
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  request_id uuid not null,
  department text not null check (department in ('Beni','Chuquisaca','Cochabamba','La Paz','Oruro','Pando','Potosí','Santa Cruz','Tarija')),
  delivery_method text not null check (delivery_method in ('pickup','delivery')),
  preferred_date date not null,
  demo_ack boolean not null check (demo_ack = true),
  subtotal numeric(10,2) not null check (subtotal > 0),
  shipping numeric(10,2) not null check (shipping in (0,25)),
  total numeric(10,2) not null check (total = subtotal + shipping),
  created_at timestamptz not null default now(),
  unique (user_id, request_id)
);
create table public.order_items (
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  size smallint not null check (size between 35 and 42),
  qty smallint not null check (qty between 1 and 10),
  unit_price numeric(10,2) not null check (unit_price > 0),
  product_name text not null,
  primary key (order_id, product_id, size)
);
create index favorites_product_idx on public.favorites(product_id);
create index cart_product_idx on public.cart_items(product_id);
create index order_items_product_idx on public.order_items(product_id);
create index orders_owner_date_idx on public.orders(user_id, created_at desc);

create function public.is_catalog_admin() returns boolean language sql stable security invoker set search_path = '' as $$
  select coalesce(auth.jwt()->'app_metadata'->>'app_role' = 'catalog_admin', false)
$$;
create function public.touch_cart() returns trigger language plpgsql set search_path = '' as $$
begin
  if TG_OP = 'DELETE' then
    perform pg_advisory_xact_lock(hashtextextended(old.user_id::text,0));
    return old;
  end if;
  if TG_OP = 'UPDATE' and (new.user_id <> old.user_id or new.product_id <> old.product_id or new.size <> old.size) then
    raise exception 'La identidad de la línea no se puede cambiar.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(new.user_id::text,0));
  new.updated_at := clock_timestamp();
  return new;
end $$;
create trigger touch_cart before insert or update or delete on public.cart_items for each row execute function public.touch_cart();

