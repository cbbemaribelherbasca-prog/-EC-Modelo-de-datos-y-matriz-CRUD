-- RPCs: el rol propietario de la función puede omitir RLS; se verifica auth.uid explícitamente.
create function public.adjust_cart_item(p_product_id bigint, p_size smallint, p_delta integer) returns void
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_qty integer; v_active boolean;
begin
  if v_uid is null then raise exception 'Se requiere una sesión.' using errcode='42501'; end if;
  if p_size is null or p_size not between 35 and 42 or p_delta is null or p_delta = 0 then raise exception 'Cantidad o talla inválida.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text,0));
  select qty into v_qty from public.cart_items where user_id=v_uid and product_id=p_product_id and size=p_size for update;
  if p_delta > 0 then
    select is_active into v_active from public.products where id=p_product_id;
    if not coalesce(v_active,false) then raise exception 'Producto no disponible.'; end if;
    if p_delta > 10 - coalesce(v_qty,0) then raise exception 'Puedes seleccionar hasta 10 pares por producto y talla.'; end if;
  end if;
  if coalesce(v_qty,0)::bigint + p_delta::bigint <= 0 then
    delete from public.cart_items where user_id=v_uid and product_id=p_product_id and size=p_size;
  elsif v_qty is null then
    insert into public.cart_items(user_id,product_id,size,qty) values(v_uid,p_product_id,p_size,p_delta);
  else
    update public.cart_items set qty=v_qty+p_delta where user_id=v_uid and product_id=p_product_id and size=p_size;
  end if;
end $$;

create function public.import_selection(p_favorites bigint[], p_cart jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_line record;
begin
  if v_uid is null then raise exception 'Se requiere una sesión.' using errcode='42501'; end if;
  if p_cart is null or jsonb_typeof(p_cart) <> 'array' then raise exception 'Selección inválida.'; end if;
  if jsonb_array_length(p_cart)>72 then raise exception 'Selección inválida.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text,0));
  insert into public.favorites(user_id,product_id)
    select v_uid,p.id from public.products p where p.is_active and p.id=any(p_favorites)
    on conflict do nothing;
  for v_line in select x.id,x.size,max(x.qty) qty from jsonb_to_recordset(p_cart) as x(id bigint,size smallint,qty smallint) group by x.id,x.size loop
    if v_line.id is null or v_line.qty is null or v_line.size is null or v_line.qty not between 1 and 10 or v_line.size not between 35 and 42 then raise exception 'Cantidad o talla inválida.'; end if;
    if exists(select 1 from public.products where id=v_line.id and is_active) then
      insert into public.cart_items(user_id,product_id,size,qty) values(v_uid,v_line.id,v_line.size,v_line.qty)
        on conflict(user_id,product_id,size) do update set qty=greatest(public.cart_items.qty,excluded.qty);
    end if;
  end loop;
end $$;

create function public.confirm_order(p_request_id uuid, p_department text, p_method text, p_date date, p_ack boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=auth.uid(); v_order public.orders; v_subtotal numeric(10,2); v_shipping numeric(10,2); v_today date := (now() at time zone 'America/La_Paz')::date;
begin
  if v_uid is null then raise exception 'Se requiere una sesión.' using errcode='42501'; end if;
  if p_request_id is null then raise exception 'Identificador de intento requerido.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text,0));
  select * into v_order from public.orders where user_id=v_uid and request_id=p_request_id;
  if found then return to_jsonb(v_order); end if;
  if p_ack is distinct from true then raise exception 'Confirma que es una demostración.'; end if;
  if p_date is null or p_date < v_today+1 or p_date > v_today+30 then raise exception 'Fecha de entrega inválida.'; end if;
  if not exists(select 1 from public.cart_items where user_id=v_uid) then raise exception 'El carrito está vacío.'; end if;
  -- Congelar los precios leídos hasta completar la transacción.
  perform p.id from public.products p join public.cart_items c on c.product_id=p.id where c.user_id=v_uid order by p.id for share of p;
  if exists(select 1 from public.cart_items c join public.products p on p.id=c.product_id where c.user_id=v_uid and not p.is_active) then raise exception 'Retira el producto no disponible.'; end if;
  select sum(c.qty*p.price) into v_subtotal from public.cart_items c join public.products p on p.id=c.product_id where c.user_id=v_uid;
  v_shipping := case when p_method='delivery' and v_subtotal<500 then 25 else 0 end;
  insert into public.orders(user_id,request_id,department,delivery_method,preferred_date,demo_ack,subtotal,shipping,total,created_at)
    values(v_uid,p_request_id,p_department,p_method,p_date,p_ack,v_subtotal,v_shipping,v_subtotal+v_shipping,clock_timestamp()) returning * into v_order;
  insert into public.order_items(order_id,product_id,size,qty,unit_price,product_name)
    select v_order.id,p.id,c.size,c.qty,p.price,p.name from public.cart_items c join public.products p on p.id=c.product_id where c.user_id=v_uid;
  return to_jsonb(v_order);
end $$;

create function public.clear_confirmed_cart(p_order_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=auth.uid(); v_created timestamptz;
begin
  if v_uid is null then raise exception 'Se requiere una sesión.' using errcode='42501'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text,0));
  select created_at into v_created from public.orders where id=p_order_id and user_id=v_uid;
  if not found then raise exception 'Pedido no disponible.' using errcode='42501'; end if;
  if exists(select 1 from public.cart_items c where c.user_id=v_uid and (c.updated_at>v_created or not exists(select 1 from public.order_items i where i.order_id=p_order_id and i.product_id=c.product_id and i.size=c.size and i.qty=c.qty))) then
    raise exception 'El carrito cambió después de confirmar. Revísalo antes de vaciarlo.';
  end if;
  delete from public.cart_items where user_id=v_uid;
end $$;
